/**
 * Syncs backend/.env → weret.code-workspace (MongoDB Atlas) + Flutter API hints.
 * Run: npm run vscode:sync
 */
import fs from "fs";
import os from "os";
import path from "path";
import { fileURLToPath } from "url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const envPath = path.join(root, "backend", ".env");
const workspacePath = path.join(root, "weret.code-workspace");
const examplePath = path.join(root, "weret.code-workspace.example");

function loadEnvFile(file) {
  const out = {};
  if (!fs.existsSync(file)) return out;
  for (const line of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const i = t.indexOf("=");
    if (i <= 0) continue;
    out[t.slice(0, i).trim()] = t.slice(i + 1).trim();
  }
  return out;
}

function detectLanIp() {
  const nets = os.networkInterfaces();
  for (const name of Object.keys(nets)) {
    for (const net of nets[name] || []) {
      const v4 = net.family === "IPv4" || net.family === 4;
      if (!v4 || net.internal) continue;
      if (net.address.startsWith("169.254.")) continue;
      return net.address;
    }
  }
  return "192.168.1.15";
}

if (!fs.existsSync(envPath)) {
  console.error("Missing backend/.env — copy from backend/.env.example first.");
  process.exit(1);
}

const env = loadEnvFile(envPath);
const mongoUri = String(env.MONGODB_URI || "").trim();
const dbName = String(env.MONGODB_DB_NAME || "weret").trim();
const port = String(env.PORT || "3000").trim();
const lanIp = detectLanIp();

if (!mongoUri) {
  console.error("MONGODB_URI is empty in backend/.env");
  process.exit(1);
}

const base = JSON.parse(fs.readFileSync(examplePath, "utf8"));
base.settings = {
  ...base.settings,
  "mdb.presetConnections": [
    {
      name: `WERET Atlas (${dbName})`,
      connectionString: mongoUri,
    },
  ],
  "mdb.defaultLimit": 25,
  "weret.apiUrlLan": `http://${lanIp}:${port}`,
  "weret.apiUrlLocal": `http://127.0.0.1:${port}`,
  "weret.apiUrlAndroidEmulator": `http://10.0.2.2:${port}`,
};

fs.writeFileSync(workspacePath, `${JSON.stringify(base, null, 2)}\n`);

const flutterEnv = `# Auto-generated by npm run vscode:sync
API_URL=http://${lanIp}:${port}
`;
fs.writeFileSync(path.join(root, "apps", "mobile-flutter", ".env.vscode"), flutterEnv);

console.log("VS Code workspace ready:");
console.log(`  Open: ${workspacePath}`);
console.log(`  MongoDB preset: WERET Atlas (${dbName})`);
console.log(`  Flutter LAN API: http://${lanIp}:${port}`);
console.log("\nIn VS Code:");
console.log("  1. File → Open Workspace from File → weret.code-workspace");
console.log("  2. Install recommended extensions (Flutter + MongoDB)");
console.log("  3. MongoDB panel → WERET Atlas → Connect");
console.log("  4. Run & Debug → Full Stack: Backend + Flutter");
